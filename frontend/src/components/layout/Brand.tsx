"use client";

import React from "react";
import Link from "next/link";

import { useStrings } from "@/components/providers/LocaleProvider";

/**
 * The wordmark.
 *
 * One component, because the brand appears in three places — the header on
 * mobile, the start sidebar on desktop, and every auth page — and three
 * hand-drawn variants is how a logo ends up three different sizes.
 *
 * THE MARK IS THE ARTWORK, NOT A LETTER IN A TILE. `public/logo.png` is the
 * product's real logo: a magnifier whose lens is filled with the calligraphic
 * `حكاوي`, a quill laid across it and a crescent over the rim.
 * `public/logo-mark-dark.png` and `public/logo-mark-light.png` are the emblem
 * cut out of that artwork — the ring, the quill and the crescent, framed square
 * — drawn for the canvas they sit on. Both are generated by
 * `scripts/generate-brand-assets.mjs` from one source, so they cannot drift
 * apart.
 *
 * The `ح`-on-amber tile that used to stand in for the mark is gone, and the
 * reason is not that the artwork is prettier. It was a PLACEHOLDER for a logo
 * that did not exist yet, drawn in the product's own palette so that the
 * layout had something to hold; a placeholder that outlasts the real thing is
 * worse than no placeholder, because the moment the real logo arrives the
 * placeholder is the thing that has to be noticed and removed. This is that
 * moment.
 *
 * THE MARK AND THE WORDMARK ARE NOT THE SAME THING, WHICH IS WHY BOTH ARE
 * SHOWN. The artwork carries the name in Arabic calligraphy — a logotype,
 * which does not change with the language of the interface — while the
 * wordmark beside it is the name in the reader's own script: `حكاوي` in
 * Arabic, `Hakawi` in English. The emblem says "this is the mark"; the wordmark
 * says "this is what it is called, in your language".
 *
 * WHY THE MARK IS A CSS BACKGROUND AND NOT AN `<img>`. The artwork is a print,
 * and a print has two grounds: it reads as drawn on the light canvas and it
 * does not read on the dark one, where the frame's violet ink is at 1.15:1 and
 * the frame disappears. So the mark has a version for each canvas, and the
 * theme — resolved before the first paint, by the bootstrap in
 * `lib/preferences.ts` — decides which one is drawn. Only CSS can act on that
 * moment: an `<img>` whose `src` follows the theme downloads the wrong
 * version first and the right one after hydration, and a browser fetches a
 * hidden image whether it is wanted or not. See `.hk-brand-mark` in
 * `globals.css`.
 *
 * The one raw `<img>` in the design system (`components/ui/RemoteImage.tsx`)
 * exists for the opposite case — a runtime host that no static allowlist can
 * name.
 *
 * WHY THE EMBLEM IS NOT ROUNDED. The artwork's own shape is a circle, and the
 * quill and the crescent break out of it at the top right; a rounded
 * container would cut them off. The radius in the design system's table
 * (`rounded-2xl` on the large brand mark) described the placeholder tile, and
 * the artwork supersedes it.
 */
export function Brand({
  href,
  size = "md",
  showName = true,
  className = "",
}: {
  href?: string;
  size?: "sm" | "md" | "lg";
  showName?: boolean;
  className?: string;
}) {
  const strings = useStrings();

  const marks = {
    sm: "size-9",
    md: "size-10",
    lg: "size-14",
  } as const;

  const names = {
    sm: "text-base",
    md: "text-xl",
    lg: "text-3xl",
  } as const;

  const mark = (
    <span aria-hidden="true" className={`${marks[size]} hk-brand-mark shrink-0`} />
  );

  const name = showName ? (
    <span className={`${names[size]} font-arabic-heading font-bold text-ink`}>{strings.shell.brand}</span>
  ) : null;

  const classes = `flex items-center gap-2 ${className}`.trim();

  if (!href) {
    return (
      <span className={classes} aria-label={showName ? undefined : strings.shell.brand}>
        {mark}
        {name}
      </span>
    );
  }

  return (
    <Link href={href} className={`${classes} rounded-lg`} aria-label={showName ? undefined : strings.shell.brand}>
      {mark}
      {name}
    </Link>
  );
}
